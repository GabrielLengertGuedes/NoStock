-- Alertas de estoque por notificacao push (Web Push com VAPID).
--
-- Uma linha por aparelho inscrito. endpoint e o endereco que o servico de push
-- do navegador deu ao aparelho; p256dh e auth sao as chaves com que a API cifra
-- o alerta para que so aquele aparelho consiga ler. O endpoint e unico: o mesmo
-- celular entrando com outro usuario troca o dono da linha em vez de duplicar.
--
-- nivel diz a partir de qual status o aparelho quer ser avisado. A ordem do
-- enum importa: a API seleciona quem tem nivel <= status do produto.
--   BAIXO       abaixo do minimo, critico ou sem estoque
--   CRITICO     critico ou sem estoque
--   SEM_ESTOQUE so quando acabar

do $$ begin
  create type public.nivel_alerta as enum ('BAIXO','CRITICO','SEM_ESTOQUE');
exception when duplicate_object then null; end $$;

create table if not exists public.inscricoes_push (
  id            bigint generated by default as identity primary key,
  usuario_id    integer       not null references public.usuarios(id) on delete cascade,
  endpoint      varchar(1000) not null,
  p256dh        varchar(200)  not null,
  auth          varchar(100)  not null,
  nivel         public.nivel_alerta not null default 'BAIXO',
  criado_em     timestamptz   not null default now(),
  atualizado_em timestamptz   not null default now(),
  constraint uk_inscricoes_push_endpoint unique (endpoint)
);

create index if not exists ix_inscricoes_push_usuario on public.inscricoes_push (usuario_id);

drop trigger if exists tg_inscricoes_push_atualizado_em on public.inscricoes_push;
create trigger tg_inscricoes_push_atualizado_em before update on public.inscricoes_push
  for each row execute function public.set_atualizado_em();

-- Mesma regra das outras tabelas (schema.sql): a API acessa por conexao direta,
-- que ignora RLS; habilitar sem policy fecha a tabela para a API publica do Supabase.
alter table public.inscricoes_push enable row level security;
revoke all on public.inscricoes_push from anon, authenticated;
