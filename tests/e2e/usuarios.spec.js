import { randomBytes } from 'node:crypto'
import { test, expect, abrirAcao } from './fixtures.js'

test('gestor cria usuário, altera papel e consulta depois de recarregar', async ({ page, entrar }) => {
  await entrar('gestor', '/usuarios')
  await page.getByRole('button', { name: 'Novo usuário', exact: true }).click()
  const dialogo = page.getByRole('dialog')
  await dialogo.getByLabel(/^Nome(?:\s*\*)?$/).fill('Pessoa nova E2E')
  await dialogo.getByLabel(/^E-mail(?:\s*\*)?$/).fill('pessoa@example.com')
  await dialogo.getByLabel(/^Senha inicial(?:\s*\*)?$/).fill(randomBytes(12).toString('hex'))
  await dialogo.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(dialogo).toHaveCount(0)
  await abrirAcao(page, 'Pessoa nova E2E', 'Editar')
  await dialogo.getByLabel(/^Papel(?:\s*\*)?$/).selectOption('GESTOR')
  await dialogo.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(dialogo).toHaveCount(0)
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: 'Pessoa nova E2E' })).toContainText('Gestor')
})

test('gestor inativa e reativa operador', async ({ page, entrar, dados }) => {
  await entrar('gestor', '/usuarios')
  await abrirAcao(page, dados.operador.nome, 'Inativar')
  await page.getByRole('dialog').getByRole('button', { name: 'Inativar', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: dados.operador.nome })).toHaveCount(0)
  const acessoInativo = await page.request.post('/api/auth/login', { data: { email: dados.operador.email, senha: dados.operador.senha } })
  expect(acessoInativo.status()).toBe(401)
  await page.getByRole('tab', { name: 'Inativos', exact: true }).click()
  await abrirAcao(page, dados.operador.nome, 'Reativar')
  await expect(page.getByRole('row').filter({ hasText: dados.operador.nome })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Ativos', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: dados.operador.nome })).toBeVisible()
})

test('gestor redefine senha e o operador entra somente com a nova', async ({ page, entrar, dados }) => {
  const novaSenha = randomBytes(12).toString('hex')
  await entrar('gestor', '/usuarios')
  await abrirAcao(page, dados.operador.nome, 'Redefinir senha')
  const dialogo = page.getByRole('dialog')
  await dialogo.getByLabel(/^Senha nova(?:\s*\*)?$/).fill(novaSenha)
  await dialogo.getByRole('button', { name: 'Salvar senha', exact: true }).click()
  await expect(dialogo).toHaveCount(0)
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel(/^E-mail(?:\s*\*)?$/).fill(dados.operador.email)
  await page.getByLabel(/^Senha(?:\s*\*)?$/).fill(dados.operador.senha)
  await page.getByRole('button', { name: 'Entrar no Sistema', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('E-mail ou senha incorretos')
  await page.getByLabel(/^Senha(?:\s*\*)?$/).fill(novaSenha)
  await page.getByRole('button', { name: 'Entrar no Sistema', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
  expect((await page.request.get('/api/auth/me')).status()).toBe(200)
})

test('último gestor não pode rebaixar a própria conta', async ({ page, entrar, dados }) => {
  await entrar('gestor', '/usuarios')
  await abrirAcao(page, dados.gestor.nome, 'Editar')
  const dialogo = page.getByRole('dialog')
  await dialogo.getByLabel(/^Papel(?:\s*\*)?$/).selectOption('OPERADOR')
  await dialogo.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(dialogo.getByRole('alert')).toContainText('último gestor ativo')
  expect((await (await page.request.get('/api/auth/me')).json()).dados.papel).toBe('GESTOR')
})
