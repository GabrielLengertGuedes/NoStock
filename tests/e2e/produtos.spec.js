import { test, expect, abrirAcao, obterProduto } from './fixtures.js'

test('operador cadastra produto e o estoque inicial aparece no histórico', async ({ page, entrar, dados }) => {
  await entrar('operador')
  await page.getByRole('link', { name: /Novo produto/ }).click()
  await page.getByLabel(/^Nome(?:\s*\*)?$/).fill('Petisco novo E2E')
  await page.getByLabel(/^Categoria(?:\s*\*)?$/).selectOption(String(dados.categoria.id))
  await page.getByLabel(/^Preço de venda(?:\s*\*)?$/).fill('15.90')
  await page.getByLabel(/^Estoque mínimo(?:\s*\*)?$/).fill('5')
  await page.getByLabel(/^Estoque inicial(?:\s*\*)?$/).fill('12')
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click()
  await expect(page).toHaveURL(/\/produtos$/)
  await page.reload()
  const linha = page.getByRole('row').filter({ hasText: 'Petisco novo E2E' })
  await expect(linha).toContainText('12 un.')
  await page.goto('/movimentacoes')
  await expect(page.getByRole('row').filter({ hasText: 'Petisco novo E2E' })).toContainText('Estoque inicial')
  await expect(page.getByRole('row').filter({ hasText: 'Petisco novo E2E' })).toContainText(dados.operador.nome)
})

test('operador edita produto mas não pode excluir', async ({ page, entrar, dados }) => {
  await entrar('operador')
  await page.getByRole('button', { name: `Ações de ${dados.produtos.critico.nome}` }).click()
  await expect(page.getByRole('menuitem', { name: 'Excluir', exact: true })).toHaveCount(0)
  await page.getByRole('menuitem', { name: 'Editar', exact: true }).click()
  await page.getByLabel(/^Estoque mínimo(?:\s*\*)?$/).fill('1')
  await page.getByLabel(/^Preço de venda(?:\s*\*)?$/).fill('25')
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click()
  await expect(page).toHaveURL(/\/produtos$/)
  await page.reload()
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.critico.nome })).toContainText('OK')
  expect(await obterProduto(page, dados.produtos.critico.id)).toMatchObject({ precoVenda: 25, estoqueMinimo: 1, quantidadeAtual: 2 })
  expect((await page.request.delete(`/api/produtos/${dados.produtos.critico.id}`)).status()).toBe(403)
})

test('busca e filtros exibem o produto correspondente', async ({ page, entrar, dados }) => {
  await entrar()
  await page.getByRole('tab', { name: 'Sem estoque', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.zerado.nome })).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.normal.nome })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Todos', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Busca', exact: true }).fill('Areia')
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.normal.nome })).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.zerado.nome })).toHaveCount(0)
})

test('gestor exclui e reativa produto preservando o histórico', async ({ page, entrar, dados }) => {
  await entrar()
  await abrirAcao(page, dados.produtos.critico.nome, 'Excluir')
  await page.getByRole('dialog').getByRole('button', { name: 'Excluir', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.critico.nome })).toHaveCount(0)
  await page.getByLabel(/^Situação(?:\s*\*)?$/).selectOption('false')
  await abrirAcao(page, dados.produtos.critico.nome, 'Reativar')
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.critico.nome })).toHaveCount(0)
  await page.getByLabel(/^Situação(?:\s*\*)?$/).selectOption('true')
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.critico.nome })).toBeVisible()
  await page.goto('/movimentacoes')
  await expect(page.getByRole('row').filter({ hasText: dados.produtos.critico.nome })).toContainText('Estoque inicial')
})
